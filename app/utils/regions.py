def normalize_region(value: str) -> str:
    cleaned = re.sub(r"\s+", " ", (value or "").strip())
    return cleaned


def federal_district_for(region: str) -> str:
    key = normalize_region(region).lower().replace("ё", "е")
    return DISTRICTS.get(key, "")
